import { App, WorkspaceWindow } from 'obsidian';
import ImageZoomDragPlugin from '../main';

// Helper to determine image eligibility based on strict rules.
export function resolveEligibleImage(event: Event): HTMLImageElement | SVGSVGElement | null {
    // 1. Get elements from composed path to handle shadow DOM or different windows
    const path = event.composedPath();
    if (!path.length) return null;

    // Use the first element as the target
    const targetNode = path[0];
    if (!(targetNode instanceof Element)) return null;
    const target = targetNode as HTMLElement;

    // If the event happened inside our controls, ignore it completely for interception
    if (target.closest && target.closest('.image-zoom-controls')) {
        return null;
    }

    // Must not be in sidebars, modals, or suggestion containers
    if (target.closest('.modal, .suggestion-container, .mod-left-split, .mod-right-split, .workspace-ribbon')) {
        return null;
    }

    // Try to find an eligible image starting from the target
    let resolvedImage: HTMLImageElement | SVGSVGElement | null = null;

    // Check if the target is already active (we should still resolve it so handlers can use it)
    if (target.classList && target.classList.contains('image-zoom-drag-active')) {
        resolvedImage = target as HTMLImageElement | SVGSVGElement;
    }

    // Find the nearest wrapper or direct element.
    let imageElement: Element | null = resolvedImage;
    if (!imageElement) {
        if (target.matches('.internal-embed.image-embed') || target.closest('.internal-embed.image-embed')) {
            const embed = target.closest('.internal-embed.image-embed');
            if (embed) {
                imageElement = embed.querySelector('img');
            }
        }
    }
    if (!imageElement) {
        imageElement = target.closest('img, .mermaid svg');
    }


    if (imageElement && (imageElement.tagName.toLowerCase() === 'img' || imageElement.tagName.toLowerCase() === 'svg')) {
        resolvedImage = imageElement as HTMLImageElement | SVGSVGElement;
    }

    if (!resolvedImage) return null;

    // Validate that it's in a markdown view (reading or live preview)
    const workspaceSplit = resolvedImage.closest(".workspace-split");
    const leafContent = resolvedImage.closest(".workspace-leaf-content");

    // Check if it is inside markdown content
    const inMarkdownView = resolvedImage.closest('.markdown-reading-view, .markdown-source-view');

    if (!workspaceSplit ||
        workspaceSplit.classList.contains("mod-left-split") ||
        workspaceSplit.classList.contains("mod-right-split") ||
        !leafContent ||
        !inMarkdownView) {
        return null;
    }

    // Exclude generic SVG icons
    if (resolvedImage.tagName.toLowerCase() === 'svg') {
        // If it's already active, it's fine
        if (resolvedImage.classList.contains('image-zoom-drag-active')) return resolvedImage;
        // Must be a mermaid diagram
        if (!resolvedImage.closest('.mermaid')) {
            return null;
        }
    }

    return resolvedImage;
}

export class ImageInteractionController {
    private plugin: ImageZoomDragPlugin;
    private app: App;
    private registeredDocuments = new Map<Document, Array<() => void>>();

    constructor(plugin: ImageZoomDragPlugin, app: App) {
        this.plugin = plugin;
        this.app = app;
    }

    public isTakeoverEnabled(): boolean {
        return this.plugin.settings.disableNativeImageInteractions;
    }

    public isDebugEnabled(): boolean {
        return this.plugin.settings.debugImageInteractions;
    }

    private logDebug(message: string, data?: any) {
        if (this.isDebugEnabled()) {
            console.log(`[Image Pan and Zoom] ${message}`, data || {});
        }
    }

    private consumeEvent(event: Event): void {
        if (event.cancelable) event.preventDefault();
        event.stopImmediatePropagation();
    }

    private handleEvent = (event: Event) => {
        // Skip if event is generated by our own reset controls
        const targetNode = event.composedPath()[0];
        if (targetNode instanceof Element) {
            const target = targetNode as HTMLElement;
            if (target.closest && target.closest('.image-zoom-controls')) {
                return;
            }
        }

        const eligibleImage = resolveEligibleImage(event);

        // For wheel, we only intercept if it's an active image
        if (event.type === 'wheel') {
            const wheelEvent = event as WheelEvent;
            if (eligibleImage && this.plugin.isImageActive(eligibleImage)) {
                if (wheelEvent.altKey) {
                    this.consumeEvent(event);
                    this.logDebug("Image interaction consumed", { eventType: event.type, reason: "alt-wheel-zoom" });
                    this.plugin.handleWheelInternal(wheelEvent, eligibleImage);
                }
            }
            return;
        }

        if (!eligibleImage) return;

        const isTakeover = this.isTakeoverEnabled();
        const isActive = this.plugin.isImageActive(eligibleImage);

        if (event.type === 'contextmenu') {
            if (isTakeover) {
                this.consumeEvent(event);
                this.plugin.showImageManagementMenu(event as MouseEvent, eligibleImage);
                this.logDebug("Image interaction consumed", { eventType: event.type, reason: "context-menu-replaced" });
            }
            return;
        }

        if (event.type === 'dragstart') {
            if (isTakeover) {
                this.consumeEvent(event);
                this.logDebug("Image interaction consumed", { eventType: event.type, reason: "dragstart-suppressed" });
            }
            return;
        }

        if (event.type === 'dblclick') {
            if (isTakeover) {
                this.consumeEvent(event);
                this.logDebug("Image interaction consumed", { eventType: event.type, reason: "dblclick-suppressed" });
            }
            return;
        }

        const mouseEvent = event as MouseEvent;

        if (event.type === 'click' || event.type === 'auxclick') {
            if (mouseEvent.altKey && mouseEvent.button === 0) {
                // Alt-click activation
                if (isTakeover) {
                    this.consumeEvent(event);
                    this.logDebug("Image interaction consumed", { eventType: event.type, reason: "alt-click-activation", active: isActive });
                }
                if (!isActive) {
                    this.plugin.activateImage(eligibleImage);
                }
            } else if (isTakeover) {
                // Suppress normal opening
                this.consumeEvent(event);
                this.logDebug("Image interaction consumed", { eventType: event.type, reason: "click-suppressed" });
            }
            return;
        }

        if (event.type === 'pointerdown' || event.type === 'mousedown') {
            // pointerdown acts as initiation blocker
            if (mouseEvent.button === 0) { // Left click
                if (isActive) {
                    if (event.type === 'mousedown') {
                        // Start panning
                        this.consumeEvent(event);
                        this.logDebug("Image interaction consumed", { eventType: event.type, reason: "pan-start" });
                        this.plugin.startPan(mouseEvent, eligibleImage);
                    } else if (isTakeover && event.type === 'pointerdown') {
                        event.stopImmediatePropagation();
                    }
                } else if (isTakeover) {
                    // Suppress competing initiation for inactive image
                    event.stopImmediatePropagation();
                    this.logDebug("Image interaction consumed", { eventType: event.type, reason: "initiation-suppressed" });
                }
            } else if (mouseEvent.button === 1 && isTakeover) { // Middle click
                // Suppress middle-click opening via pointerdown/mousedown
                this.consumeEvent(event);
                this.logDebug("Image interaction consumed", { eventType: event.type, reason: "middle-click-suppressed" });
            }
            return;
        }
    }


    private handleMouseMove = (event: Event) => {
        this.plugin.handleMouseMove(event as MouseEvent);
    };

    private handleMouseUp = (event: Event) => {
        this.plugin.handleMouseUp(event as MouseEvent);
    };

    private handleKeyDown = (event: Event) => {
        const keyboardEvent = event as KeyboardEvent;
        if (keyboardEvent.key === 'Escape') {
            this.plugin.handleEscape(keyboardEvent);
        }
    };

    private handleBlur = (event: Event) => {
        this.plugin.endCurrentDrag('window-blur');
    };

    public registerDocument(doc: Document) {
        if (this.registeredDocuments.has(doc)) return;

        const disposers: Array<() => void> = [];

        const register = (target: EventTarget, type: string, handler: EventListenerOrEventListenerObject, options: AddEventListenerOptions) => {
            target.addEventListener(type, handler, options);
            disposers.push(() => target.removeEventListener(type, handler, options));
        };

        // Capture phase listeners for routing
        register(doc, 'click', this.handleEvent, { capture: true });
        register(doc, 'auxclick', this.handleEvent, { capture: true });
        register(doc, 'dblclick', this.handleEvent, { capture: true });
        register(doc, 'pointerdown', this.handleEvent, { capture: true });
        register(doc, 'mousedown', this.handleEvent, { capture: true });
        register(doc, 'dragstart', this.handleEvent, { capture: true });
        register(doc, 'contextmenu', this.handleEvent, { capture: true });

        // Wheel needs passive: false
        register(doc, 'wheel', this.handleEvent, { capture: true, passive: false });

        // Lifecycle listeners (not capturing)
        register(doc, 'mousemove', this.handleMouseMove, { capture: false });
        register(doc, 'mouseup', this.handleMouseUp, { capture: false });
        register(doc, 'keydown', this.handleKeyDown, { capture: false });

        const win = doc.defaultView;
        if (win) {
            register(win, 'blur', this.handleBlur, { capture: false });
        }

        this.registeredDocuments.set(doc, disposers);

        this.logDebug("Interaction controller registered for document", { documentCount: this.registeredDocuments.size });
    }

    public unregisterDocument(doc: Document) {
        const disposers = this.registeredDocuments.get(doc);
        if (disposers) {
            disposers.forEach(dispose => dispose());
            this.registeredDocuments.delete(doc);
        }
    }

    public getRegisteredDocuments(): Document[] {
        return Array.from(this.registeredDocuments.keys());
    }

    public dispose() {
        for (const doc of this.registeredDocuments.keys()) {
            this.unregisterDocument(doc);
        }
        this.logDebug("Interaction controller disposed", { documentCount: this.registeredDocuments.size });
    }
}
